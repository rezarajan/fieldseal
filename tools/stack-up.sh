#!/usr/bin/env bash
# Starts the local stack: generates the secrets (once; a later release's new secrets are appended),
# refuses to start on a Keycloak volume made from an older realm, renders the services' environment from
# the manifest, builds and loads the images with Nix, starts compose and waits for the endpoints
# (Keycloak, the factory, the intake app, the log and the web app), then publishes the examples,
# issues the example rosters and assigns their cohorts (tools/stack-run.sh seed, issue, assign).
#
#   tools/stack-up.sh                 (normally: just up)
#
# Environment: FIELDSEAL_CONTAINER_ENGINE=docker|podman, FIELDSEAL_BIN (a fieldseal CLI to use instead of building one),
#              FIELDSEAL_SKIP_IMAGE_BUILD=1 (reuse the images already loaded).
set -euo pipefail
# shellcheck source=stack-engine.sh
. "$(dirname "${BASH_SOURCE[0]}")/stack-engine.sh"

MANIFEST="$ROOT/examples/deployments/local-stack.yaml"
GEN="$LOCAL/.generated"
ENV_SECRETS="$LOCAL/.env.secrets"
mkdir -p "$GEN"; : > "$GEN/stack-timing.tsv"; : > "$GEN/stack-timing.txt"
FS="$(stage cli "$ROOT/tools/stack-cli.sh")"

rand_hex() { head -c "$1" /dev/urandom | od -An -vtx1 | tr -d ' \n'; }

# Secrets (generated once, git-ignored; the manifest only names them) and configuration (one env
# file per service, rendered from the manifest). Run by `stage`, so every step ends in `|| die`.
secrets_and_render() {
  # The file is made once; a secret that a later release added is appended to an existing file.
  if [ ! -f "$ENV_SECRETS" ]; then
    ( umask 077; echo "# Generated by tools/stack-up.sh. Local development only. Never commit." > "$ENV_SECRETS" ) \
      || die "could not write $ENV_SECRETS"
    say "generated $ENV_SECRETS"
  fi
  local name
  for name in KC_BOOTSTRAP_ADMIN_PASSWORD FIELDSEAL_SECRET_FACTORY_OIDC_CLIENT_SECRET FIELDSEAL_SECRET_INTAKE_OIDC_CLIENT_SECRET; do
    if ! grep -q "^$name=" "$ENV_SECRETS"; then
      case "$name" in KC_BOOTSTRAP_ADMIN_PASSWORD) n=16 ;; *) n=24 ;; esac
      ( umask 077; echo "$name=$(rand_hex "$n")" >> "$ENV_SECRETS" ) || die "could not write $ENV_SECRETS"
      say "added $name to $ENV_SECRETS"
    fi
  done
  "$FS" deployment validate "$MANIFEST" >/dev/null || die "the manifest does not validate: fieldseal deployment validate $MANIFEST"
  mkdir -p "$GEN"; find "$GEN" -maxdepth 1 -name '*.env' -delete || die "could not clear $GEN"
  "$FS" deployment render "$MANIFEST" --environment development --out "$GEN" >/dev/null || die "could not render $MANIFEST"
  say "rendered the environment of $(basename "$MANIFEST") to deploy/local/.generated"
  # The web service's device accepts the publishers the intake component's policy engine does:
  # the same two lists, copied under the web app's names, so the values stay in the manifest.
  sed -n 's/^FIELDSEAL_INTAKE_ALLOWED_\(BUILDERS\|SOURCES\)=/FIELDSEAL_WEB_ALLOWED_\1=/p' "$GEN/intake.env" > "$GEN/web.env" \
    || die "could not write $GEN/web.env"
}
stage secrets+render secrets_and_render

# Keycloak imports the realm only into an empty volume (`--import-realm` skips a realm that
# exists), so a changed realm file never reaches an old volume. The digest of the file the
# volume was made from is kept in deploy/local/.state/realm.sha256 (`just purge` removes it).
REALM_FILE="$LOCAL/keycloak/fieldseal-realm.json"
REALM_RECORD="$LOCAL/.state/realm.sha256"
REALM_DIGEST="$(sha256sum "$REALM_FILE" | cut -d' ' -f1)"
REALM_RECORD_NEEDED=0
check_realm() {
  if [ -f "$REALM_RECORD" ]; then
    [ "$(cat "$REALM_RECORD")" = "$REALM_DIGEST" ] || die "the Keycloak realm changed; run \`just purge\`"
  elif "$ENGINE" volume ls -q 2>/dev/null | grep -qx 'fieldseal-local_keycloak-data'; then
    die "the Keycloak realm changed; run \`just purge\`"
  else
    REALM_RECORD_NEEDED=1
  fi
}
check_realm

if [ "${FIELDSEAL_SKIP_IMAGE_BUILD:-0}" = 1 ]; then say "== reusing the loaded images"; else "$ROOT/tools/stack-images.sh"; fi

say "== starting the stack with ${COMPOSE[*]}"
stage compose-up compose up -d
if [ "$REALM_RECORD_NEEDED" = 1 ]; then
  mkdir -p "$(dirname "$REALM_RECORD")" && printf '%s\n' "$REALM_DIGEST" > "$REALM_RECORD" \
    || die "could not write $REALM_RECORD"
fi

wait_for() { # url what seconds
  local i=0
  while ! curl -fsS -o /dev/null --max-time 3 "$1" 2>/dev/null; do
    i=$((i + 1)); [ "$i" -lt "$3" ] || die "$2 did not become ready at $1 (tools/stack-compose.sh logs)"
    sleep 1
  done
  say "ready: $2 ($1)"
}
stage wait-keycloak wait_for http://localhost:8180/realms/fieldseal/.well-known/openid-configuration "Keycloak (realm fieldseal)" 240
stage wait-factory wait_for http://localhost:8080/readyz "factory" 120
stage wait-intake wait_for http://localhost:8480/healthz "intake" 120
stage wait-log wait_for http://localhost:9001/checkpoint "transparency log" 120
stage wait-web wait_for http://127.0.0.1:8090/instruments "web app" 120

# The production order (Technical Plan 8): publish, then issue the rosters, then assign. Each step
# is idempotent. The two operator sign-ins use a passkey that is reset on every run, which costs
# nothing here because no one has signed in by hand yet.
stage seed "$ROOT/tools/stack-run.sh" seed || die "the seed step failed (tools/stack-run.sh seed)"
stage issue "$ROOT/tools/stack-run.sh" issue || die "the issue step failed (tools/stack-run.sh issue)"
stage assign "$ROOT/tools/stack-run.sh" assign || die "the assign step failed (tools/stack-run.sh assign)"

stage_report

cat <<MSG

The stack is up (engine: $ENGINE).

  Portal:            http://localhost:8080
  Keycloak console:  http://localhost:8180/admin   (admin / KC_BOOTSTRAP_ADMIN_PASSWORD in deploy/local/.env.secrets)
  Web app + device:  http://127.0.0.1:8090   (choose a survey, register, collect, upload)
  Intake uploads:    http://localhost:8480   (devices upload here)
  Results reader:    http://localhost:8481   (sign in as product-owner; download the results files)
  Transparency log:  http://localhost:9001

The examples are published, the example rosters issued and their cohorts assigned to the
collector's account (product-owner).

Next:  just seed     publish the sample instruments (again: nothing changes)
       just demo     register a device with a passkey, capture, upload, verify the receipts
       just down     stop (keeps the registered device, the passkey and the log);  just purge  forgets all
MSG
