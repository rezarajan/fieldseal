#!/usr/bin/env bash
# Starts the local stack: generates the secrets (once), renders the services' environment from
# the manifest, builds and loads the images with Nix, starts compose and waits for the endpoints.
#
#   tools/stack-up.sh                 (normally: just up)
#
# Environment: FIELDSEAL_CONTAINER_ENGINE=docker|podman, FIELDSEAL_BIN (a fieldseal CLI to use instead of building one),
#              FIELDSEAL_SKIP_IMAGE_BUILD=1 (reuse the images already loaded).
set -euo pipefail
# shellcheck source=stack-engine.sh
. "$(dirname "${BASH_SOURCE[0]}")/stack-engine.sh"

MANIFEST="$ROOT/examples/deployments/local-stack.yaml"
GEN="$LOCAL/.generated"
ENV_SECRETS="$LOCAL/.env.secrets"
mkdir -p "$GEN"; : > "$GEN/stack-timing.tsv"; : > "$GEN/stack-timing.txt"
FS="$(stage cli "$ROOT/tools/stack-cli.sh")"

rand_hex() { head -c "$1" /dev/urandom | od -An -vtx1 | tr -d ' \n'; }

# Secrets (generated once, git-ignored; the manifest only names them) and configuration (one env
# file per service, rendered from the manifest). Run by `stage`, so every step ends in `|| die`.
secrets_and_render() {
  if [ ! -f "$ENV_SECRETS" ]; then
    ( umask 077
      { echo "# Generated by tools/stack-up.sh. Local development only. Never commit."
        echo "KC_BOOTSTRAP_ADMIN_PASSWORD=$(rand_hex 16)"
        echo "FIELDSEAL_SECRET_FACTORY_OIDC_CLIENT_SECRET=$(rand_hex 24)"
      } > "$ENV_SECRETS" ) || die "could not write $ENV_SECRETS"
    say "generated $ENV_SECRETS"
  fi
  "$FS" deployment validate "$MANIFEST" >/dev/null || die "the manifest does not validate: fieldseal deployment validate $MANIFEST"
  mkdir -p "$GEN"; find "$GEN" -maxdepth 1 -name '*.env' -delete || die "could not clear $GEN"
  "$FS" deployment render "$MANIFEST" --environment development --out "$GEN" >/dev/null || die "could not render $MANIFEST"
  say "rendered the environment of $(basename "$MANIFEST") to deploy/local/.generated"
}
stage secrets+render secrets_and_render

if [ "${FIELDSEAL_SKIP_IMAGE_BUILD:-0}" = 1 ]; then say "== reusing the loaded images"; else "$ROOT/tools/stack-images.sh"; fi

say "== starting the stack with ${COMPOSE[*]}"
stage compose-up compose up -d

wait_for() { # url what seconds
  local i=0
  while ! curl -fsS -o /dev/null --max-time 3 "$1" 2>/dev/null; do
    i=$((i + 1)); [ "$i" -lt "$3" ] || die "$2 did not become ready at $1 (tools/stack-compose.sh logs)"
    sleep 1
  done
  say "ready: $2 ($1)"
}
stage wait-keycloak wait_for http://localhost:8180/realms/fieldseal/.well-known/openid-configuration "Keycloak (realm fieldseal)" 240
stage wait-factory wait_for http://localhost:8080/readyz "factory" 120
stage wait-intake wait_for http://localhost:8480/healthz "intake upload endpoint" 120
stage wait-log wait_for http://localhost:9001/checkpoint "transparency log" 120
stage wait-web wait_for http://localhost:8090/instruments "web app" 120

stage_report

cat <<MSG

The stack is up (engine: $ENGINE).

  Portal:            http://localhost:8080
  Keycloak console:  http://localhost:8180/admin   (admin / KC_BOOTSTRAP_ADMIN_PASSWORD in deploy/local/.env.secrets)
  Web app + device:  http://localhost:8090   (choose a survey, register, collect, upload)
  Intake upload:     http://localhost:8480
  Transparency log:  http://localhost:9001

Next:  just seed     publish the sample instrument through the log
       just demo     register a device with a passkey, capture, upload, verify the receipts
       just down     stop (keeps the registered device, the passkey and the log);  just purge  forgets all
MSG
