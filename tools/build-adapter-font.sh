#!/usr/bin/env bash
# Regenerates crates/adapters/html/src/fonts.css: Nunito Sans (SIL OFL 1.1) subset to Latin and
# Latin Extended at weights 400/600/700/800, as woff2 data: URIs, so the HTML adapter's page
# stays self-contained (no font request). Scripts the font lacks (Arabic, ...) fall back to the
# system stack. Usage: tools/build-adapter-font.sh   (needs nix; run from the repository root)
set -euo pipefail
here="$(cd "$(dirname "$0")/.." && pwd)"
out="$here/crates/adapters/html"
src="$(nix build nixpkgs#nunito-sans --no-link --print-out-paths)/share/fonts/truetype/NunitoSans/static"
unicodes="U+0020-007E,U+00A0-017F,U+0180-024F,U+02C6,U+02DA,U+02DC,U+1E00-1EFF,U+2013-2014,U+2018-201E,U+2022,U+2026,U+20AC,U+2212,U+2190,U+2192"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
{
  echo "/* Nunito Sans, SIL Open Font License 1.1 (crates/adapters/html/fonts/OFL.txt), subset to Latin and Latin Extended."
  echo "   Generated by tools/build-adapter-font.sh; do not edit. */"
} > "$out/src/fonts.css"
for pair in 400:Regular 600:SemiBold 700:Bold 800:ExtraBold; do
  w="${pair%%:*}"; n="${pair##*:}"
  nix shell --impure --expr 'let p = (builtins.getFlake "nixpkgs").legacyPackages.${builtins.currentSystem}; in p.python3.withPackages (x: [ x.fonttools x.brotli ])' --command \
    pyftsubset "$src/NunitoSans-$n.ttf" --unicodes="$unicodes" --flavor=woff2 \
    --layout-features='kern,liga,tnum,lnum' --no-hinting --desubroutinize --output-file="$tmp/$w.woff2"
  cp "$tmp/$w.woff2" "$out/fonts/NunitoSans-$n.subset.woff2"
  b64="$(base64 -w0 "$tmp/$w.woff2")"
  printf '@font-face{font-family:"Nunito Sans";font-style:normal;font-weight:%s;font-display:swap;src:url(data:font/woff2;base64,%s) format("woff2")}\n' "$w" "$b64" >> "$out/src/fonts.css"
done
wc -c "$out/src/fonts.css"
