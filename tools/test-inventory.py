#!/usr/bin/env python3
"""Every test, and the requirement that justifies it (docs/reference/test-inventory.md).

A test is justified when it names at least one requirement the specs define, in its name
(`fn ins_126_repeat_expands_in_list_order`) or in a `// covers: INS-126` comment on the lines
just above it (doc comments and attributes may sit in between). A requirement ID that no spec
defines does not justify anything.

  tools/test-inventory.py            write docs/reference/test-inventory.md
  tools/test-inventory.py --check    exit 1 if any test is unjustified or the document is stale
  tools/test-inventory.py --report   the unjustified tests and the requirements with the most tests
"""
import argparse
import collections
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SPECS = ROOT / "docs/reference/spec"
OUT = ROOT / "docs/reference/test-inventory.md"
DEFINED = re.compile(r"^\s*(?:-|\|)\s*\*\*([A-Z]+-\d+[a-z]?)\*\*\s*(.*)$")
INVARIANT = re.compile(r"^\|\s*(INV-\d+)\s*\|\s*(.*)$")
NAME_ID = re.compile(r"(?:^|_)(adr)_(\d{4})(?=_|$)|(?:^|_)(inv)_(\d{1,2})(?=_|$)|(?:^|_)([a-z]{2,4})_(\d{3}[a-z]?)(?=_|$)")
COVERS = re.compile(r"//\s*covers:\s*(.*)$")
ID = re.compile(r"\b([A-Z]{2,4})-(\d{1,4}[a-z]?)(?:\s*(?:\.\.|-)\s*\1-(\d{3}))?")
TEST_ATTR = re.compile(r"^\s*#\[(?:test|tokio::test)\b")
FN = re.compile(r"^\s*(?:pub\s+)?(?:async\s+)?fn\s+([a-z0-9_]+)")
ADR = re.compile(r"^(\d{4})-.*\.md$")


def defined_ids() -> dict[str, str]:
    ids: dict[str, str] = {}
    for spec in sorted(SPECS.glob("*.md")):
        for line in spec.read_text(encoding="utf-8").splitlines():
            m = DEFINED.match(line) or INVARIANT.match(line)
            if m:
                text = re.sub(r"\s+", " ", m.group(2)).strip()
                ids[m.group(1)] = f"{spec.stem}: {text[:110]}"
    for adr in (ROOT / "docs/explanation/adr").glob("*.md"):
        m = ADR.match(adr.name)
        if m:
            ids[f"ADR-{m.group(1)}"] = f"ADR {m.group(1)}"
    return ids


def ids_in_comment(text: str) -> list[str]:
    out = []
    for m in ID.finditer(text):
        prefix, start, end = m.group(1), m.group(2), m.group(3)
        if end and start.isdigit():
            out += [f"{prefix}-{n:03d}" for n in range(int(start), int(end) + 1)]
        else:
            out.append(f"{prefix}-{start}")
    return out


def ids_in_name(name: str) -> list[str]:
    out = []
    for m in NAME_ID.finditer(name):
        if m.group(1):
            out.append(f"ADR-{m.group(2)}")
        elif m.group(3):
            out.append(f"INV-{int(m.group(4))}")
        else:
            out.append(f"{m.group(5).upper()}-{m.group(6)}")
    return out


def tests() -> list[tuple[str, int, str, list[str]]]:
    found = []
    for path in sorted(ROOT.glob("crates/**/*.rs")):
        if "/target/" in str(path):
            continue
        lines = path.read_text(encoding="utf-8").splitlines()
        for i, line in enumerate(lines):
            if not TEST_ATTR.match(line):
                continue
            j = i + 1
            while j < len(lines) and not FN.match(lines[j]):
                j += 1
            if j == len(lines):
                continue
            name = FN.match(lines[j]).group(1)
            ids = ids_in_name(name)
            k = i - 1
            while k >= 0 and (lines[k].strip().startswith(("///", "//", "#[")) or not lines[k].strip()):
                c = COVERS.search(lines[k])
                if c:
                    ids += ids_in_comment(c.group(1))
                if not lines[k].strip():
                    break
                k -= 1
            found.append((str(path.relative_to(ROOT)), j + 1, name, sorted(set(ids))))
    return found


def render(rows, defined) -> str:
    out = [
        "# Test inventory",
        "",
        "<!-- Generated by `tools/test-inventory.py`; do not edit by hand. `just test` checks it. -->",
        "",
        "Every test and the requirement that justifies it. A test exists only to prove a requirement of",
        "the specs (or an ADR); the requirement is in its name or in a `// covers:` comment above it.",
        "",
        f"{len(rows)} tests prove {len({i for r in rows for i in r[3] if i in defined})} requirements.",
        "",
        "| Test | Requirements | What they require |",
        "|---|---|---|",
    ]
    for path, line, name, ids in rows:
        known = [i for i in ids if i in defined]
        why = "; ".join(f"{i} ({defined[i].split(':')[0]})" for i in known[:3])
        out.append(f"| `{name}` ([{pathlib.Path(path).name}:{line}](../../{path}#L{line})) | {', '.join(known) or '—'} | {why or '**unjustified**'} |")
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--report", action="store_true")
    a = ap.parse_args()
    defined = defined_ids()
    rows = tests()
    unjustified = [r for r in rows if not any(i in defined for i in r[3])]
    if a.report:
        per = collections.Counter(i for r in rows for i in r[3] if i in defined)
        print(f"{len(rows)} tests; {len(unjustified)} unjustified")
        for path, line, name, ids in unjustified:
            print(f"  {path}:{line} {name} {ids or ''}")
        print("requirements with the most tests:", per.most_common(15))
        return 0
    doc = render(rows, defined)
    if a.check:
        bad = 0
        for path, line, name, ids in unjustified:
            print(f"unjustified test: {path}:{line} {name}" + (f" (names {', '.join(ids)}, which no spec defines)" if ids else ""))
            bad += 1
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != doc:
            print("docs/reference/test-inventory.md is stale: run tools/test-inventory.py")
            bad += 1
        return 1 if bad else 0
    OUT.write_text(doc, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} tests, {len(unjustified)} unjustified")
    return 0


if __name__ == "__main__":
    sys.exit(main())
